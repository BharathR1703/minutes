// Generates src/lib/seed/ami-raw.ts from /tmp/ami-cache/ami.json (written by
// scripts/fetch-ami.mjs). Data: the public AMI Meeting Corpus —
// edinburghcstr/ami on Hugging Face, ihm config, test split — real utterances
// with real timestamps and dataset speaker ids. The dataset carries no
// calendar dates, so a fixed placeholder date per meeting is set here and
// labeled as such in the UI/README.
import { writeFileSync } from "node:fs";

const PLACEHOLDER_DATES = {
  // the AMI corpus was collected in 2005; the dataset rows carry no dates
  EN2002a: "2005-02-07T10:00:00Z",
  EN2002b: "2005-02-08T10:00:00Z",
  EN2002c: "2005-02-09T10:00:00Z",
};

// AMI word transcripts are ALL CAPS — normalize to sentence case, "I" back
function norm(s) {
  let t = s.trim().replace(/\s+/g, " ");
  if (t.length > 3 && t === t.toUpperCase()) {
    t = t.toLowerCase().charAt(0).toUpperCase() + t.toLowerCase().slice(1);
    t = t.replace(/\bi\b/g, "I").replace(/\bi'd\b/g, "I'd").replace(/\bi'll\b/g, "I'll")
      .replace(/\bi'm\b/g, "I'm").replace(/\bi've\b/g, "I've");
  }
  return t;
}

const raw = JSON.parse(await (await import("node:fs/promises")).readFile("/tmp/ami-cache/ami.json", "utf8"));
const meetings = raw
  .map((m) => {
    // keep the first 45 minutes, drop near-empty turns, cap length
    const kept = m.utterances
      .filter((u) => u.t < 2700 && (u.text ?? "").trim().length > 2)
      .slice(0, 450)
      .map((u) => ({ t: Math.round(u.t * 10) / 10, dur: u.dur, speaker: u.speaker, text: norm(u.text) }));
    return { id: m.id, meetingDate: PLACEHOLDER_DATES[m.id] ?? "2005-02-07T10:00:00Z", utterances: kept };
  })
  .filter((m) => m.utterances.length >= 50);

const header = `// AUTO-GENERATED by scripts/generate-ami-raw.mjs — do not edit by hand.
// Source: the public AMI Meeting Corpus (edinburghcstr/ami on Hugging Face,
// ihm config, test split): real utterances, real timestamps, dataset speaker
// ids. The dataset carries no calendar dates; the dates below are labeled
// placeholders within the corpus collection year (2005), surfaced honestly in
// the UI footnote and README.
export type AmiRaw = {
  id: string;
  meetingDate: string;
  utterances: { t: number; dur: number; speaker: string; text: string }[];
};
export const AMI_RAW: AmiRaw[] = `;

writeFileSync(
  "src/lib/seed/ami-raw.ts",
  header + JSON.stringify(meetings, null, 1) + ";\n",
);
console.log(`wrote src/lib/seed/ami-raw.ts (${meetings.length} meetings)`);
for (const m of meetings) {
  const dur = Math.max(...m.utterances.map((u) => u.t + u.dur));
  console.log(`${m.id}: ${m.utterances.length} turns, ${Math.round(dur / 60)} min, speakers ${[...new Set(m.utterances.map((u) => u.speaker))].join(", ")}`);
}
console.log("sample turns:", JSON.stringify(meetings[0]?.utterances.slice(0, 2), null, 1));